import type { APIRoute } from 'astro';
import { existsSync } from 'node:fs';
import { join } from 'node:path';

/**
 * /sitemap.xml — built from the pages that actually exist in src/pages, so a page is
 * listed only once it is published and nothing has to be edited by hand.
 * URLs use the preferred https://www.rs1.uk address with no trailing slash.
 * No <lastmod>: it is only worth adding with accurate modification dates.
 */
const pageFiles = Object.keys(import.meta.glob('./**/*.astro'));

/** Routes that must never be listed (error pages, anything not meant for search). */
const EXCLUDED = new Set(['/404', '/500']);

const paths = pageFiles
  .map((file) => {
    const path = file.replace(/^\./, '').replace(/\.astro$/, '').replace(/\/index$/, '');
    return path === '' ? '/' : path;
  })
  .filter((path) => !EXCLUDED.has(path) && !path.includes('['))
  .sort((a, b) => (a === '/' ? -1 : b === '/' ? 1 : a.localeCompare(b)));

export const GET: APIRoute = ({ site }) => {
  // A hand-written public/sitemap.xml would be copied over this generated one.
  // Stop the build rather than publish a stale file by accident.
  if (existsSync(join(process.cwd(), 'public', 'sitemap.xml'))) {
    throw new Error(
      'Delete public/sitemap.xml — the sitemap is generated by src/pages/sitemap.xml.ts and the static file would override it.',
    );
  }

  const origin = site ?? new URL('https://www.rs1.uk');
  const urls = paths
    .map((path) => `  <url><loc>${new URL(path, origin).href}</loc></url>`)
    .join('\n');

  const body = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls}
</urlset>
`;

  return new Response(body, {
    headers: { 'Content-Type': 'application/xml; charset=utf-8' },
  });
};
